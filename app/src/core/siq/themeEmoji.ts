/** Пары по умолчанию: яркие и нейтральные, чтобы подходили к любой теме. */
const FALLBACK: [string, string][] = [
  ["🎯", "✨"], ["🔥", "💥"], ["🎲", "🍀"], ["⚡", "🌟"], ["🎪", "🎉"], ["🧩", "💫"], ["🚀", "🌈"], ["🦄", "✨"], ["🍭", "🎈"], ["💎", "🔮"],
];

/** Есть ли в строке эмодзи (пиктограмма). */
export function hasEmoji(s: string): boolean {
  return /\p{Extended_Pictographic}/u.test(s);
}

function hash(s: string): number {
  let h = 2166136261;
  for (const ch of s) h = Math.imul(h ^ ch.codePointAt(0)!, 16777619);
  return h >>> 0;
}

/** Два разных подходящих эмодзи для названия: [перед, после]. */
export function themeEmojiPair(name: string): [string, string] {
  const low = name.toLowerCase().replace(/ё/g, "е");
  const words = low.split(/[^\p{L}\p{N}]+/u).filter(Boolean);
  let best: string[] | null = null;
  let bestAt = Infinity;
  for (const [roots, emoji] of TOPICS) {
    for (const r of roots) {
      const root = r.replace(/ё/g, "е");
      // корень из двух слов («новый год») ищем во всей строке, остальные — началом слова. Короткому корню
      // даём не больше трёх букв окончания: «коты», «котики» — да, «который» — нет
      const at = root.includes(" ") ? low.indexOf(root) : words.findIndex((w) => w.startsWith(root)
        && (root.length > 3 || w.length - root.length <= 3) && (root.length > 2 || w === root));
      if (at >= 0 && at < bestAt) { best = emoji; bestAt = at; }
    }
  }
  const h = hash(low);
  if (!best) return FALLBACK[h % FALLBACK.length];
  const a = best[h % best.length];
  const rest = best.filter((e) => e !== a);
  return [a, rest[(h >>> 8) % rest.length]];
}

/** «Кино» → «🎬 Кино 🍿». Уже есть эмодзи или название пустое — не трогаем. */
export function decorateThemeName(name: string): string {
  const t = name.trim();
  if (!t || hasEmoji(t)) return name;
  const [a, b] = themeEmojiPair(t);
  return `${a} ${t} ${b}`;
}

/** Эмодзи вместе с модификаторами: ZWJ-склейки, вариационный селектор, тон кожи. */
const EMOJI_RUN = /[\p{Extended_Pictographic}\u200D\uFE0F\u{1F3FB}-\u{1F3FF}]+/u;

/** Кусок названия для показа: эмодзи рисуются отдельно (свой шрифт и размер), текст — как есть. */
export interface NamePart { emoji: boolean; text: string }

/** Название темы для показа на табло: эмодзи в начале и в конце приклеены к соседнему слову неразрывным
 *  пробелом — в узкой колонке они не падают на отдельную строку. Само название в паке не меняется. */
export function themeNameParts(name: string): NamePart[] {
  const parts: NamePart[] = [];
  const re = new RegExp(EMOJI_RUN.source, "gu");
  let last = 0;
  for (const m of name.matchAll(re)) {
    if (m.index! > last) parts.push({ emoji: false, text: name.slice(last, m.index) });
    parts.push({ emoji: true, text: m[0] });
    last = m.index! + m[0].length;
  }
  if (last < name.length) parts.push({ emoji: false, text: name.slice(last) });
  // пробелы, соседние с эмодзи, — неразрывные
  for (let i = 0; i < parts.length; i++) {
    const p = parts[i];
    if (p.emoji) continue;
    if (parts[i - 1]?.emoji) p.text = p.text.replace(/^\s+/, "\u00A0");
    if (parts[i + 1]?.emoji) p.text = p.text.replace(/\s+$/, "\u00A0");
  }
  return parts;
}
